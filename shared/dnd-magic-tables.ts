export type SlotProgression = 'none' | 'full' | 'half' | 'third' | 'pact';

/** The single-class half/third rows follow these full-caster rows after their own unlock. */
export function dndSlotTable(progression: SlotProgression, level: number, edition: DndEdition) {
  const row =
    progression === 'full'
      ? fullSlots[level - 1]
      : progression === 'half' && (level >= 2 || edition === '2024')
        ? fullSlots[Math.ceil(level / 2) - 1]
        : progression === 'third' && level >= 3
          ? fullSlots[Math.ceil(level / 3) - 1]
          : undefined;
  return Array.from({ length: 9 }, (_, index) => row?.[index] ?? 0);
}

